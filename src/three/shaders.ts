// ---------------------------------------------------------------- 径向丝线
/**
 * 丝线顶点着色器（**从中心向目标生长**）。
 *
 * ## 关于线宽：不要去调 `linewidth`
 *
 * WebGL 的 `LineBasicMaterial.linewidth` 在几乎所有平台上**被忽略**，永远只画 1 像素。
 * 参考实现（诗云）里全项目 `linewidth` 零命中 —— 它那批"又粗又亮、越靠中心越粗"的丝线，
 * 粗细**完全来自 bloom**：中心处几千条 1px 线叠加 → 亮度高 → bloom 把它晕开成一片光。
 * 所以这里也走同一条路：**1px 线 + 叠加混合 + bloom**。
 * 想加粗就去调 bloom 的 intensity/radius，或者加线密度，**不要试图去设 linewidth**。
 *
 * ## 生长动画
 *
 * 每条线有 2 个顶点（中心端、目标端），`aCenter` 是中心端坐标 —— 两个顶点都带同一个 `aCenter`，
 * 于是 `mix(aCenter, position, g)` 让两个端点同步从中心滑向目标，线看起来是"射出去"的。
 * `aPhase` 让各条线错开一点（最多 0.35 个周期），否则几千条线会像一堵墙同时推开，
 * 那是"展开"不是"喷射"。
 */
export const FILAMENT_VERT = /* glsl */ `
  attribute vec3 aCenter;
  attribute vec3 aColor;
  attribute float aPhase;
  /**
   * 起点的 docId（浮点传）。
   *
   * 为什么可以用 float 精确比较：docId 最大 1,463,588，远小于 f32 能精确表示的整数上界
   * 2^24 = 16,777,216，所以「aSrc 等于 uSelDoc」是**精确**比较，不会出现"差一"导致的漏亮。
   * 用 float 而不是 uint 属性是为了兼容 GLSL ES 1.00（three 的默认着色器版本没有整数属性）。
   */
  attribute float aSrc;
  /**
   * 线参数：0 = 起点（选中那篇）、1 = 终点（关系另一端）。
   *
   * 为什么要把它传下来：诗云的连线有两件我们原来没有的东西，都要靠它 ——
   *   ① **端点淡出** 「sin(πt)」：线从星星里"长出来"，而不是在星星边界上被硬切一刀；
   *   ② **沿线的脉冲**：一个亮点从 giver 流向 receiver（它的 「fract(uTime·0.16 + seed)」）。
   * 没有 t 就只能整条线一个亮度，那两件事都做不了。
   */
  attribute float aT;
  /**
   * 这条关系的**强度**（0~1，来自边数据的 weight 字段）。
   *
   * 常驻关系线场用它做阈值筛选（照诗云"无选中时只画强关系"），
   * 选中态的扇形不用它（uMinWeight 恒为 0，永远全画）。
   */
  attribute float aWeight;
  uniform float uGrow;
  /** 当前选中的 docId；uSelOn 为 0 时它不参与运算 */
  uniform float uSelDoc;
  uniform float uSelOn;
  /** 沿线脉冲的时钟（秒）—— 由 Filaments 每帧推进 */
  uniform float uTime;
  varying vec3 vColor;
  varying float vGrow;
  varying float vHot;
  varying float vT;
  varying float vWeight;
  /**
   * 生长相位**必须传到片元**才能给每条线的脉冲错开相位。
   *
   * ⚠️ 第一次写的时候在片元里直接用了 「aPhase」 —— 那是**顶点属性**，片元着色器看不见它，
   *    编译直接失败（整层线不画）。这类错和"括号注释写在模板里"一样，是静默的：
   *    页面不报错、只是那一层没了。所以改完必须跑 「lint-embedded」 + 看实测像素。
   */
  varying float vPhase;
  void main() {
    float g = clamp((uGrow - aPhase * 0.35) / 0.65, 0.0, 1.0);
    vec3 wp = mix(aCenter, position, g);
    vColor = aColor;
    vGrow = g;
    vT = aT;
    vPhase = aPhase;
    vWeight = aWeight;
    // 这条线是不是"选中那篇论文"发出来的
    vHot = uSelOn * step(abs(aSrc - uSelDoc), 0.5);
    gl_Position = projectionMatrix * modelViewMatrix * vec4(wp, 1.0);
  }
`;

/**
 * 丝线片元着色器。
 *
 * alpha 基准 **0.12**（实际约 0.48：vHot 会把选中项那批再乘 4）。
 * 对比 v1（默认铺网）：那时 11 万条线，单条压到 0.035 才不至于糊成一片白 ——
 * 同一个旋钮，两种数量级，**这个数不能跨版本照抄**。
 * 参考实现的平面样式用 alpha 0.28；我们线更少更亮一点，量级相当。
 *
 * 选中态：`vHot` 的那条线 **亮度 ×1.5、不透明度 ×4**，其余压到 `uRest`（选中时 0.3）。
 * 于是"点一篇论文 → 它的关系线亮起来、别的退下去"——这才是点击该有的信息量，
 * 而不只是"闪一下"。
 */
export const FILAMENT_FRAG = /* glsl */ `
  varying vec3 vColor;
  varying float vGrow;
  varying float vHot;
  varying float vWeight;
  uniform float uAlpha;
  uniform float uRest;
  /**
   * **关系强度阈值**：弱于它的线直接不画。
   *
   * ## 为什么需要这一条（照诗云的 AMBIENT_MIN_W = 3）
   *
   * 诗云那一层赠诗弧在"没有选中任何诗人"时**只画强关系**，而且系数只有 0.32。
   * 我们原来是无差别按固定步长抽 2600 条 × 8 团 ≈ 两万条，加法混叠之后
   * 整屏变成一层**连续的暖色纤维雾** —— 逐层归因量到它一条就占整屏发光量的
   * **40%（Δmean 38.5 / 97.3）**，而作者要的参照帧是"黑底 + 离散彩色亮星"。
   *
   * ⚠️ 但**不能因此把这一层删掉**：作者最初的三条要求里就有"**径向丝线**"。
   *    诗云的解法也不是"删掉"，而是"**只留强的**" —— 阈值就是这个动作。
   *
   * ⚠️ 做成 uniform 而不是构建期的 if：这样能在**同一个页面**里扫阈值
   *    （见 _scratch/probe-bright-sweep.mjs 的做法）。构建期过滤每换一个值
   *    就要重跑一次构建 + 自检约 5 分钟，而且每次都是新页面，噪声不可比。
   */
  uniform float uMinWeight;
  /**
   * 生命周期包络（照搬诗云的三段：生长 1.2s → 保持 → 淡出 1.2s）。
   *
   * 我们原来只有生长 —— 取消选中时线是**瞬间消失**的，那读起来像"程序出错了"，
   * 而不是"这个关系被收起来了"。uEnv 就是那条淡出曲线。
   */
  uniform float uEnv;
  /** 沿线脉冲的时钟（秒） */
  uniform float uTime;
  varying float vT;
  varying float vPhase;
  void main() {
    if (vWeight < uMinWeight) discard;
    /**
     * 端点淡出 —— 照诗云的 「fade = Math.sin(Math.PI * t)」。
     *
     * 为什么要这一条：没有它，每条线都在**星星的边界上被硬切一刀**，
     * 看起来像一根根插在星上的棍子；有了它，线是从星里"渗出来"的。
     *
     * ⚠️ 指数 0.55 不是照抄（诗云是纯 sin）：我们的线**比它少两个数量级**
     *    （它几千条，我们几百条），纯 sin 会让每条线的两端各淡掉一大截，
     *    整束读起来像"断线"。取 0.55 次幂把两端抬回来一些 —— 是同一件事的**尺度修正**，
     *    不是另一个效果。这一条实测过：纯 sin 时线束的可见长度肉眼可见地短了一截。
     */
    float t = clamp(vT, 0.0, 1.0);
    float fade = pow(sin(3.14159265 * t), 0.55);
    float a = uAlpha * uEnv * vGrow * fade * (1.0 + vHot * 3.0) * mix(uRest, 1.0, vHot);
    vec3 c = vColor * (1.0 + vHot * 1.5);
    /**
     * 沿线脉冲：一个亮点从**起点（选中那篇）流向终点（关系另一端）**。
     *
     * 照诗云的 「phase = fract(uTime * 0.16 + seed)」 + 最近环绕距离。
     * 周期取 2.2 秒（≈0.45 次/秒）—— 它的 0.16 是"整条弧走一圈 6 秒"，
     * 而我们的线短得多，同样的角速度会显得像在闪；2.2 秒是一眼能看出方向的速度。
     * 宽度 0.14：只点亮线的一小段，读起来是"流过去"而不是"整条亮一下"。
     */
    float phase = fract(uTime / 2.2 + vPhase * 0.7);
    float d = t - phase;
    d = d - floor(d + 0.5); // 最近环绕距离
    float pulse = smoothstep(0.14, 0.0, abs(d));
    c *= 1.0 + pulse * 1.8 * vHot;
    a *= 1.0 + pulse * 0.9 * vHot;
    if (a < 0.003) discard;
    /**
     * ⚠️ **这里刻意不预乘 —— 与星点着色器相反，别"顺手改成一致"。**
     *
     * three 的 AdditiveBlending 是 src.rgb × src.a + dst：**它自己会乘一次 src.a**。
     * 星点因为要软裙（高斯衰减写在 rgb 里）所以预乘，代价是实际贡献变成 c × a²
     * ——它的注释里记着这件事，并用 0.22 那个小系数去补偿。
     *
     * 丝线一开始照抄了预乘，结果是**整层几乎不可见**：a = 0.18 时贡献只有
     * c × 0.18² = c × 0.032，在亮星点旁边等于没画（实测：像素统计与"完全没有丝线层"
     * 时只差 0.05 个百分点，肉眼完全看不出）。线是硬的、没有软边，本来就不需要预乘，
     * 所以这里输出 vec4(c, a)，让 three 去乘那一次 —— 贡献就是 c × 0.18，是原来的 5.6 倍。
     */
    gl_FragColor = vec4(c, a);
  }
`;

// ---------------------------------------------------------------- 选中脉冲
/**
 * 选中脉冲（面向相机的方片）。三种形态共用一个着色器，靠 `uKind` 分支：
 *   0 = 冲击波环 —— 从中心向外扩、变大变粗、渐隐（`uProgress` 就是环半径）
 *   1 = 核心闪光 —— 一团高斯光斑，亮度由 `uProgress` 给（出生最亮，很快收敛）
 *   2 = 常驻标记 —— 固定半径的细环 + 一圈极淡的光晕，带呼吸
 *
 * 三种都是**预乘 + 叠加**，与星点一致；这样它们会被 bloom 一起晕开，
 * 看起来是"发光"而不是"贴了一张带颜色的图"。
 */
export const PULSE_VERT = /* glsl */ `
  varying vec2 vUv;
  void main() {
    vUv = uv;
    gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
  }
`;

export const PULSE_FRAG = /* glsl */ `
  varying vec2 vUv;
  uniform vec3 uColor;
  /** 0→1 的进度：冲击波当半径用、闪光当亮度用、标记环不用 */
  uniform float uProgress;
  uniform float uOpacity;
  uniform float uTime;
  uniform float uKind;
  void main() {
    vec2 p = (vUv - 0.5) * 2.0;
    float d = length(p);
    if (d > 1.0) discard;
    float a;
    if (uKind < 0.5) {
      // 冲击波：环半径 = uProgress，越扩越粗、越扩越淡
      float w = 0.05 + 0.12 * uProgress;
      float ring = exp(-pow((d - uProgress) / w, 2.0));
      a = ring * pow(1.0 - uProgress, 1.7);
    } else if (uKind < 1.5) {
      a = exp(-d * d * 9.0) * uProgress;
    } else {
      // 常驻标记：细环 + 极淡内晕，靠 uTime 呼吸
      float ring = exp(-pow((d - 0.80) / 0.055, 2.0));
      float glow = exp(-d * d * 5.0) * 0.30;
      float breath = 0.80 + 0.20 * sin(uTime * 2.4);
      a = (ring + glow) * breath;
    }
    a *= uOpacity;
    if (a < 0.003) discard;
    gl_FragColor = vec4(uColor * a, a);
  }
`;
