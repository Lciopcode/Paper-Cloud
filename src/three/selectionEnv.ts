/**
 * 论文云 · 选中包络
 * ============================================================================
 * 一个 0~1 的共享标量：**"此刻选中一颗星的程度"**。0 = 没选中，1 = 完全选中。
 *
 * ## 它解决什么问题
 *
 * 点开一颗星之后要能**看清它的关系线**。但星团中心本来就是一团强光
 * （核球粒子 + 大柔光 Sprite + bloom），关系线只有几十条、又细，
 * 在核心附近会被整个吞掉 —— 实测：选中一颗靠近核心的星时，
 * 截图里几乎找不到线（`_scratch/probe-click-feedback.mjs` 专门挑最靠近核心的那颗，
 * 因为这个场景最容易坏）。
 *
 * 参考实现没有这个问题，因为它选中的是**诗人星**、周围是它自己的行星云；
 * 而我们的论文散布在整个星系里，光核就在旁边。
 *
 * 解法是**把非关系层压暗**：星云与核心柔光按 `1 - 0.7 × env` 退下去，
 * 关系线于是自己浮出来。这也是参考实现在别的场景里用过的同一招
 * （选中诗人后弧网切成 ego-net、其余退下去）。
 *
 * ## 为什么是模块级单例，而不是 store 字段
 *
 * 它**不是应用状态**，而是"这一帧的渲染强度" —— 每帧都在变，
 * 放进 store 会让每帧触发一次 React 重渲染（那是性能灾难）。
 * 它的推进者**只有一个**：`Filaments`（生命周期状态机在那里，
 * 生长/保持/淡出的曲线也由它算）。其余图层只读。
 */
export const selectionEnv = {
  /** 当前包络值（0~1） */
  value: 0,
  /** 包络属于哪个学科（只有本团的图层才该被压暗） */
  domain: "",
};
